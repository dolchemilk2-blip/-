(function () {
  const root = document.documentElement;
  const reduce = () => !!(window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches);
  // Флаг «JS работает»: только с ним reveal прячет элементы (без JS всё видно сразу)
  if ('IntersectionObserver' in window && !reduce()) root.classList.add('home-js');

  const curLang = () => {
    if (window.NP && NP.lang) return NP.lang();
    let l = null; try { l = localStorage.getItem('lang'); } catch (e) { /* private */ }
    return TRANSLATIONS[l] ? l : 'ru';
  };
  const t = (k) => (TRANSLATIONS[curLang()] || TRANSLATIONS.ru)[k] || TRANSLATIONS.ru[k] || '';

  // --- Переводы атрибутов: data-i18n-alt / data-i18n-aria (main.js переводит только текст) ---
  function applyAttrs() {
    document.querySelectorAll('[data-i18n-alt]').forEach(el => { const v = t(el.getAttribute('data-i18n-alt')); if (v) el.alt = v; });
    document.querySelectorAll('[data-i18n-aria]').forEach(el => { const v = t(el.getAttribute('data-i18n-aria')); if (v) el.setAttribute('aria-label', v); });
  }

  // --- Scene engine: IO-gated rAF пишет --p (0→1) на секцию; CSS читает var(--p,1) ---
  function initScenes() {
    if (reduce() || !('IntersectionObserver' in window)) return;
    const scenes = Array.from(document.querySelectorAll('[data-scene]'));
    if (!scenes.length) return;
    const live = new Set();
    let raf = 0;
    const frame = () => {
      raf = 0;
      const vh = window.innerHeight || 1;
      live.forEach(el => {
        const r = el.getBoundingClientRect();
        // 0 — верх секции у нижнего края экрана, 1 — верх секции на 25% высоты экрана
        const p = Math.min(1, Math.max(0, (vh - r.top) / (vh * 0.75)));
        el.style.setProperty('--p', p.toFixed(3));
      });
    };
    const request = () => { if (!raf && live.size) raf = requestAnimationFrame(frame); };
    const io = new IntersectionObserver(entries => {
      entries.forEach(e => { if (e.isIntersecting) live.add(e.target); else live.delete(e.target); });
      request();
    }, { rootMargin: '10% 0px 10% 0px' });
    scenes.forEach(el => { el.style.setProperty('--p', '0'); io.observe(el); });
    frame();
    // Секции, уже пролистанные выше (reload в середине страницы), — финальное состояние
    scenes.forEach(el => { if (el.getBoundingClientRect().bottom < 0) el.style.setProperty('--p', '1'); });
    window.addEventListener('scroll', request, { passive: true });
    window.addEventListener('resize', request);
  }

  // --- Reveal: opacity + подъём 16px, один раз, stagger ≤40ms, не более 6 в группе ---
  function initReveal() {
    if (!root.classList.contains('home-js')) return;
    const els = Array.from(document.querySelectorAll('main [data-reveal]'));
    const groups = new Map();
    els.forEach(el => {
      const key = el.closest('section');
      const list = groups.get(key) || []; list.push(el); groups.set(key, list);
      el.style.setProperty('--ri', String(Math.min(list.length - 1, 5)));
    });
    const io = new IntersectionObserver(entries => {
      entries.forEach(e => {
        if (!e.isIntersecting) return;
        // Соседи в том же ряду (горизонтальный скролл на мобильном) появляются вместе
        const sibs = e.target.parentElement ? Array.from(e.target.parentElement.children).filter(x => x.hasAttribute('data-reveal')) : [e.target];
        sibs.forEach(x => { x.classList.add('is-in'); io.unobserve(x); });
      });
    }, { rootMargin: '0px 0px -8% 0px', threshold: 0.01 });
    els.forEach(el => {
      // Уже на экране при загрузке — показываем без анимации
      if (el.getBoundingClientRect().top < window.innerHeight * 0.92) el.classList.add('is-in', 'is-instant');
      else io.observe(el);
    });
  }

  // --- Глава «Цвет шерсти»: радиогруппа (CSS :has делает всю работу), клавиатура — мгновенно ---
  function initCoat() {
    const sec = document.getElementById('coat');
    if (!sec) return;
    const seg = sec.querySelector('.coat-seg');
    const sync = () => {
      const c = (sec.querySelector('input[name="coat"]:checked') || {}).value || 'white';
      sec.setAttribute('data-coat', c);   // запасной вариант для браузеров без :has
    };
    seg.addEventListener('pointerdown', () => sec.classList.remove('is-kbd'));
    seg.addEventListener('keydown', () => sec.classList.add('is-kbd'));
    seg.addEventListener('change', sync);
    sync();
  }

  // --- Вкладки «О Nature's Protection»: ARIA и стрелки (клик обрабатывает main.js) ---
  function initTabs() {
    const tabs = Array.from(document.querySelectorAll('.home-values .brand-tab'));
    if (!tabs.length) return;
    const sync = () => tabs.forEach(tb => {
      const on = tb.classList.contains('is-active');
      tb.setAttribute('aria-selected', on ? 'true' : 'false');
      tb.tabIndex = on ? 0 : -1;
    });
    tabs.forEach((tb, i) => {
      tb.addEventListener('click', () => setTimeout(sync, 0));
      tb.addEventListener('keydown', e => {
        let n = -1;
        if (e.key === 'ArrowRight') n = (i + 1) % tabs.length;
        else if (e.key === 'ArrowLeft') n = (i - 1 + tabs.length) % tabs.length;
        else if (e.key === 'Home') n = 0;
        else if (e.key === 'End') n = tabs.length - 1;
        if (n < 0) return;
        e.preventDefault();
        tabs[n].click(); tabs[n].focus();
      });
    });
    sync();
  }

  // --- Форма: честная отправка через почтовую программу (main.js потом показывает #formOk и сбрасывает) ---
  function initForm() {
    const form = document.getElementById('contactForm');
    if (!form) return;
    form.addEventListener('submit', () => {
      const d = new FormData(form);
      const body = (d.get('message') || '') + '\n\n— ' + (d.get('name') || '') + ' <' + (d.get('email') || '') + '>';
      const href = 'mailto:info@naturesprotection.az?subject=' + encodeURIComponent(t('home.contact.subject')) +
        '&body=' + encodeURIComponent(body);
      try { window.location.href = href; } catch (e) { /* ignore */ }
    });
  }

  // --- Бургер: закрытие по Escape и при уходе фокуса ---
  function initBurger() {
    const burger = document.getElementById('burger');
    const nav = document.getElementById('nav');
    if (!burger || !nav) return;
    document.addEventListener('keydown', e => {
      if (e.key === 'Escape' && nav.classList.contains('is-open')) { burger.click(); burger.focus(); }
    });
  }

  // --- Шапка: волосяная линия только после прокрутки ---
  function initHeader() {
    const h = document.getElementById('header');
    if (!h) return;
    let raf = 0;
    const upd = () => { raf = 0; h.classList.toggle('is-scrolled', window.scrollY > 8); };
    window.addEventListener('scroll', () => { if (!raf) raf = requestAnimationFrame(upd); }, { passive: true });
    upd();
  }

  document.addEventListener('DOMContentLoaded', () => {
    applyAttrs();
    initCoat();
    initScenes();
    initReveal();
    initTabs();
    initForm();
    initBurger();
    initHeader();
  });
  document.addEventListener('np:lang', applyAttrs);
})();
